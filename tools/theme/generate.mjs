import * as mcu from '@material/material-color-utilities';
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const statusTokens = JSON.parse(readFileSync(new URL('../../tokens/material3/extended-color-schemes.json', import.meta.url)));
const roles = JSON.parse(readFileSync(new URL('../../tokens/material3/color-scheme-roles.json', import.meta.url)));
export const variants = {tonalSpot: mcu.SchemeTonalSpot, fidelity: mcu.SchemeFidelity, content: mcu.SchemeContent, monochrome: mcu.SchemeMonochrome, neutral: mcu.SchemeNeutral, vibrant: mcu.SchemeVibrant, expressive: mcu.SchemeExpressive, rainbow: mcu.SchemeRainbow, fruitSalad: mcu.SchemeFruitSalad};
export function extended(seed) {
  const result = {light: {}, dark: {}};
  for (const [name, hex] of Object.entries(statusTokens.seeds)) {
    const group = mcu.customColor(mcu.argbFromHex(seed), {name, value: mcu.argbFromHex(hex), blend: true});
    const cap = name[0].toUpperCase() + name.slice(1);
    for (const mode of ['light', 'dark']) {
      for (const [role, value] of Object.entries(group[mode])) {
        const key = {color: name, onColor: `on${cap}`, colorContainer: `${name}Container`, onColorContainer: `on${cap}Container`}[role];
        result[mode][key] = mcu.hexFromArgb(value).toUpperCase();
      }
    }
  }
  return result;
}
/** Generate MCU 0.4.0 standard-contrast schemes, including harmonized status colors. */
export function generate(seed, variant = 'tonalSpot') {
  if (!/^#[0-9a-fA-F]{6}$/.test(seed)) throw new Error('seed must be #RRGGBB');
  if (!Object.hasOwn(variants, variant)) throw new Error(`Unknown variant: ${variant}`);
  const result = {sourceColor: seed.toUpperCase(), variant, materialColorUtilities: '0.4.0', contrastLevel: 0};
  for (const mode of ['light', 'dark']) {
    const scheme = new variants[variant](mcu.Hct.fromInt(mcu.argbFromHex(seed)), mode === 'dark', 0);
    result[mode] = Object.fromEntries(roles.map(role => [role, mcu.hexFromArgb(scheme[role]).toUpperCase()]));
  }
  result.extended = extended(seed);
  return result;
}
/** Emit a standalone Swift source file to add to an application target. */
export function swiftSource(data) {
  return `// Generated by tools/theme/generate.mjs (MCU 0.4.0).\nimport MaterialDesignColorCore\n\n/// Build-time generated brand themes.\nenum GeneratedMaterialTheme {\n` + ['light', 'dark'].map(mode => {
    const core = Object.entries(data[mode]).map(([r,h]) => `      .${r}: "${h}"`).join(',\n');
    const ext = Object.entries(data.extended[mode]).map(([r,h]) => `      .${r}: "${h}"`).join(',\n');
    return `  /// ${mode} theme generated from ${data.sourceColor}.\n  static let ${mode}: MaterialTheme = {\n    // All literals are validated by the generator.\n    let scheme = try! MaterialColorScheme.custom(appearance: .${mode}, roles: [\n${core}\n    ]).overridingExtended([\n${ext}\n    ])\n    return MaterialTheme(colorScheme: scheme, sourceColor: try! MaterialColor(name: "sourceColor", hex: "${data.sourceColor}"))\n  }()\n`;
  }).join('\n') + '}\n';
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [seed, variant = 'tonalSpot', output] = process.argv.slice(2);
  const data = generate(seed, variant);
  const content = output?.endsWith('.swift') ? swiftSource(data) : JSON.stringify(data, null, 2) + '\n';
  if (output) writeFileSync(output, content); else process.stdout.write(content);
}
